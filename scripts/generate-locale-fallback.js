#!/usr/bin/env node
// Regenerates locale_fallback_en.js from _locales/en/messages.json.
//
// #211: chrome.i18n.getMessage() has no fallback option - if the browser's
// active locale (e.g. es/fi/he) is missing a key, it returns "" rather than
// falling back to default_locale, even though manifest.json declares "en"
// as the default. The only way to get fallback behavior is a JS-side copy
// of the English text the wrapper _() (shared.js) can check when Chrome's
// own lookup comes back empty. This script derives that copy from the real
// en/messages.json rather than hand-maintaining a second copy that could
// drift out of sync.
//
// Usage:
//   node scripts/generate-locale-fallback.js
//
// Run this whenever _locales/en/messages.json changes. Not wired into any
// automatic build step (this project has none, by design - see CLAUDE.md) -
// a manual, documented regeneration step instead, matching how
// build-release-zip.js is also run by hand.
"use strict";

const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const SOURCE = path.join(ROOT, "_locales", "en", "messages.json");
const OUTPUT = path.join(ROOT, "locale_fallback_en.js");

const messages = JSON.parse(fs.readFileSync(SOURCE, "utf8"));

// Only "message" and "placeholders" are ever read by the _() fallback path
// (shared.js) - "description" entries (translator-facing notes, not used
// at runtime) are dropped so this file only carries what's actually needed.
const trimmed = {};
for (const key in messages) {
    if (!Object.prototype.hasOwnProperty.call(messages, key)) continue;
    const entry = { message: messages[key].message };
    if (messages[key].placeholders) {
        entry.placeholders = messages[key].placeholders;
    }
    trimmed[key] = entry;
}

const header = `// AUTO-GENERATED by scripts/generate-locale-fallback.js from
// _locales/en/messages.json - do not hand-edit. Re-run that script after
// changing the English locale file to keep this in sync.
//
// #211: used by _() (shared.js) as the fallback source when
// chrome.i18n.getMessage() returns "" for a key missing from the browser's
// active (non-English) locale - see that script's own comment for why this
// needs to be a bundled copy rather than a live lookup.
`;

const body = "var EN_FALLBACK_MESSAGES = " + JSON.stringify(trimmed, null, 4) + ";\n";

fs.writeFileSync(OUTPUT, header + "\n" + body);
console.log(`Wrote ${OUTPUT} (${Object.keys(trimmed).length} keys) from ${SOURCE}`);
